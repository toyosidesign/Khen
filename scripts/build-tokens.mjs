#!/usr/bin/env node
/**
 * build-tokens.mjs — generate the token outputs from the single source of truth.
 *
 *   packages/tokens/src/index.ts          <- edit this, and only this
 *          │
 *          ├─→ tokens.css                 CSS custom properties
 *          └─→ figma-variables.json       Figma variable import
 *
 * These two files used to be maintained by hand, and had drifted: the Figma
 * export carried 3 of 10 brand shades, 3 of 12 neutrals, and no spacing, type
 * or shadow at all — while claiming to mirror index.ts. Generating them removes
 * the possibility.
 *
 *   node scripts/build-tokens.mjs           write the outputs
 *   node scripts/build-tokens.mjs --check   fail if they are stale (CI)
 *
 * Node >= 22.6 strips the types when importing the .ts directly, so the values
 * come from the real module rather than a parse of it.
 */

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import tokens from "../packages/tokens/src/index.ts";

const ROOT = path.resolve(import.meta.dirname, "..");
const SRC = path.join(ROOT, "packages/tokens/src");
const CSS_OUT = path.join(SRC, "tokens.css");
const FIGMA_OUT = path.join(SRC, "figma-variables.json");

const { colors, spacing, radius, typography, shadow } = tokens;

/* ── tokens.css ──
 * Existing consumers (the Tailwind preset, templates/landing) reference
 * --color-*, --font-*, --radius-* and --shadow-* by name, so those names are
 * fixed. Single-shade colour groups additionally get a bare alias, because
 * the hand-written file exposed --color-success rather than -success-500.
 */
function buildCss() {
  const L = [];
  L.push("/* GENERATED by scripts/build-tokens.mjs — do not edit by hand. */");
  L.push("/* Source of truth: packages/tokens/src/index.ts */");
  L.push(":root {");

  for (const [group, shades] of Object.entries(colors)) {
    const keys = Object.keys(shades);
    L.push(`  /* ${group} */`);
    if (keys.length === 1) L.push(`  --color-${group}: ${shades[keys[0]]};`);
    for (const k of keys) L.push(`  --color-${group}-${k}: ${shades[k]};`);
  }

  L.push("  /* spacing */");
  for (const [k, v] of Object.entries(spacing)) L.push(`  --space-${k}: ${v};`);

  L.push("  /* radius */");
  for (const [k, v] of Object.entries(radius)) L.push(`  --radius-${k}: ${v};`);

  L.push("  /* type */");
  for (const [k, v] of Object.entries(typography.fontFamily)) L.push(`  --font-${k}: ${v};`);
  for (const [k, v] of Object.entries(typography.fontSize)) L.push(`  --text-${k}: ${v};`);
  for (const [k, v] of Object.entries(typography.fontWeight)) L.push(`  --weight-${k}: ${v};`);
  for (const [k, v] of Object.entries(typography.lineHeight)) L.push(`  --leading-${k}: ${v};`);

  L.push("  /* shadow */");
  for (const [k, v] of Object.entries(shadow)) L.push(`  --shadow-${k}: ${v};`);

  L.push("}");
  return L.join("\n") + "\n";
}

/* ── figma-variables.json ── */

const rem = (v) => (typeof v === "string" && v.endsWith("rem") ? parseFloat(v) * 16 : v);
const dim = (v) => ({ $type: "dimension", $value: rem(v) });

function buildFigma() {
  const color = {};
  for (const [group, shades] of Object.entries(colors)) {
    color[group] = Object.fromEntries(
      Object.entries(shades).map(([k, v]) => [k, { $type: "color", $value: v }])
    );
  }
  return {
    $description:
      "GENERATED by scripts/build-tokens.mjs from packages/tokens/src/index.ts. " +
      "Import into Figma via a variables-import plugin. Do not edit by hand.",
    color,
    spacing: Object.fromEntries(Object.entries(spacing).map(([k, v]) => [k, dim(v)])),
    radius: Object.fromEntries(Object.entries(radius).map(([k, v]) => [k, dim(v)])),
    fontFamily: Object.fromEntries(
      Object.entries(typography.fontFamily).map(([k, v]) => [k, { $type: "fontFamily", $value: v }])
    ),
    fontSize: Object.fromEntries(Object.entries(typography.fontSize).map(([k, v]) => [k, dim(v)])),
    fontWeight: Object.fromEntries(
      Object.entries(typography.fontWeight).map(([k, v]) => [k, { $type: "number", $value: Number(v) }])
    ),
    lineHeight: Object.fromEntries(
      Object.entries(typography.lineHeight).map(([k, v]) => [k, { $type: "number", $value: Number(v) }])
    ),
    shadow: Object.fromEntries(
      Object.entries(shadow).map(([k, v]) => [k, { $type: "shadow", $value: v }])
    ),
  };
}

/* ── run ── */

const css = buildCss();
const figma = JSON.stringify(buildFigma(), null, 2) + "\n";
const check = process.argv.includes("--check");

const read = async (p) => { try { return await readFile(p, "utf8"); } catch { return null; } };

if (check) {
  const stale = [];
  if ((await read(CSS_OUT)) !== css) stale.push("tokens.css");
  if ((await read(FIGMA_OUT)) !== figma) stale.push("figma-variables.json");
  if (stale.length) {
    console.error(`\n  stale token output: ${stale.join(", ")}\n  run \`pnpm tokens:build\`\n`);
    process.exit(1);
  }
  console.log("\n  token outputs are up to date\n");
} else {
  await writeFile(CSS_OUT, css);
  await writeFile(FIGMA_OUT, figma);
  const vars = (css.match(/^\s*--/gm) || []).length;
  const count = (o) => Object.values(o).reduce((n, v) => n + Object.keys(v).length, 0);
  console.log(`\n  tokens.css             ${vars} custom properties`);
  console.log(`  figma-variables.json   ${count(buildFigma().color)} colours + spacing, radius, type, shadow\n`);
}
